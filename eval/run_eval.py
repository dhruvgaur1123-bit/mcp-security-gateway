"""Replays eval/cases.jsonl through the gateway's decision logic and reports measured results.

Usage:  python eval/run_eval.py [--policy policy.yaml] [--out eval/RESULTS.md]
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from mcpgw.policy import Policy  # noqa: E402
from mcpgw.proxy import Checker  # noqa: E402


def decide(checker: Checker, case: dict) -> str:
    stage, payload = case["stage"], case["payload"]
    if stage == "result":
        _, decision, _ = checker.check_result({"content": [{"type": "text", "text": payload}]})
        return decision                      # allow | block | redact
    if stage == "args":
        d = checker.check_call(case["tool"], payload)
        return "block" if d.action == "block" else ("redact" if d.arguments != payload else "allow")
    if stage == "tool_desc":
        return "block" if checker.tool_definition_score(payload) >= checker.policy.injection_threshold else "allow"
    raise ValueError(stage)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", default=str(ROOT / "policy.yaml"))
    ap.add_argument("--cases", default=str(ROOT / "eval" / "cases.jsonl"))
    ap.add_argument("--out", default=str(ROOT / "eval" / "RESULTS.md"))
    a = ap.parse_args()

    checker = Checker(Policy.load(a.policy))
    cases = [json.loads(l) for l in Path(a.cases).read_text().splitlines() if l.strip()]
    by_cat, misses = defaultdict(lambda: [0, 0]), []
    for c in cases:
        got = decide(checker, c)
        ok = got == c["expect"]
        by_cat[c["category"]][0] += ok
        by_cat[c["category"]][1] += 1
        if not ok:
            misses.append((c, got))

    def tot(cats):
        return sum(by_cat[k][0] for k in cats), sum(by_cat[k][1] for k in cats)

    atk = ["direct_injection", "obfuscated_injection", "tool_poisoning", "sensitive_args", "hard_paraphrased"]
    atk_core = [k for k in atk if k != "hard_paraphrased"]
    ben = ["benign", "benign_hard"]
    (ab, an), (cb, cn), (bb, bn), (pb, pn) = tot(atk), tot(atk_core), tot(ben), tot(["pii_in_result"])
    fp, fpn = bn - bb, bn

    lines = ["# Evaluation results", "",
             f"Cases: {len(cases)} (generated by `eval/build_cases.py`). Policy: `{Path(a.policy).name}`.", "",
             "| Category | Correct | Total | Rate |", "|---|---|---|---|"]
    for k in atk + ben + ["pii_in_result"]:
        ok, n = by_cat[k]
        lines.append(f"| {k} | {ok} | {n} | {ok / n:.0%} |")
    lines += ["", "## Summary", "",
              f"- Attack block rate, all attack categories: **{ab}/{an} ({ab / an:.0%})**",
              f"- Attack block rate, excluding `hard_paraphrased`: **{cb}/{cn} ({cb / cn:.0%})**",
              f"- False positives on benign calls/results: **{fp}/{fpn} ({fp / fpn:.0%})**",
              f"- PII/secret redaction rate on results: **{pb}/{pn} ({pb / pn:.0%})**", ""]
    if misses:
        lines += ["## Misses (expected -> got)", ""]
        for c, got in misses:
            lines.append(f"- `{c['id']}` [{c['stage']}] expected **{c['expect']}**, got **{got}**: `{str(c['payload'])[:90]}`")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
